-- Map/nearby primitive for a later interactive map. Radius is capped to avoid accidental huge scans.
create or replace function public.nearby_places(city_slug text, lat double precision, long double precision, radius_m integer default 500, max_results integer default 50)
returns table(
 id uuid,name text,category_id text,area text,lat double precision,long double precision,dist_meters double precision
)
set search_path=''
language sql
stable
as $$
 select p.id,p.name,p.category_id,p.area,
  extensions.st_y(p.location::extensions.geometry) as lat,
  extensions.st_x(p.location::extensions.geometry) as long,
  extensions.st_distance(p.location,extensions.st_point(long,lat)::extensions.geography) as dist_meters
 from public.places p
 join public.cities c on c.id=p.city_id
 where c.slug=city_slug
  and p.status='published' and p.visibility='public'
  and extensions.st_dwithin(p.location,extensions.st_point(long,lat)::extensions.geography,least(greatest(radius_m,50),20000))
 order by p.location operator(extensions.<->) extensions.st_point(long,lat)::extensions.geography
 limit least(greatest(max_results,1),200)
$$;

grant execute on function public.nearby_places(text,double precision,double precision,integer,integer) to anon,authenticated;

