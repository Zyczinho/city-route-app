import {readFile,writeFile} from 'node:fs/promises';

// Lists which important places still lack enrichment data. Reads only the repository; no external APIs.
const cityId=process.argv[2];
if(!cityId)throw new Error('Usage: node scripts/generate-enrichment-report.mjs <city-id>');
const base=`data/cities/${cityId}`;
const read=async p=>JSON.parse(await readFile(p,'utf8'));
const [places,anchors,routes]=await Promise.all([read(`${base}/places.json`),read(`${base}/anchors.json`),read(`${base}/routes.json`)]);

const STAY=new Set(['hotel','hostel','apartment','guesthouse']);
const FIELDS=['image','rating','reviewCount','website','openingHours','description','area'];
const anchorIds=new Set(anchors.map(a=>a.id)),routeStops=new Set(routes.flatMap(r=>r.stops));
const routeCount=id=>routes.filter(r=>r.stops.includes(id)).length;

// Squares, parks, bridges and free outdoor sights have no website or opening hours to find.
const publicSpace=p=>['neighborhood','park','architecture'].includes(p.categoryId)||(['landmark','viewpoint'].includes(p.categoryId)&&(p.tags||[]).includes('free'));
const missingFor=p=>{
  const ratings=p.ratings||[];
  const checks={
    image:!p.image,
    rating:!ratings.some(r=>Number.isFinite(r.value)),
    reviewCount:!ratings.some(r=>Number.isInteger(r.reviewCount)),
    website:!publicSpace(p)&&!p.website,
    openingHours:!STAY.has(p.categoryId)&&!publicSpace(p)&&!p.metadata?.osmTags?.opening_hours,
    description:String(p.description||'').trim().length<40,
    area:!String(p.area||'').trim()
  };
  return FIELDS.filter(f=>checks[f]);
};
const priorityFor=p=>p.top||routeStops.has(p.id)?'high':anchorIds.has(p.id)||p.metadata?.osmTags?.wikidata||p.description?'medium':'low';

const rows=places.map(p=>({p,missing:missingFor(p),priority:priorityFor(p)}));
const countMissing=list=>Object.fromEntries(FIELDS.map(f=>[f,list.filter(r=>r.missing.includes(f)).length]));
const order={high:0,medium:1,low:2};
const listed=rows.filter(r=>r.priority!=='low'&&r.missing.length)
  .sort((a,b)=>order[a.priority]-order[b.priority]||routeCount(b.p.id)-routeCount(a.p.id)||b.missing.length-a.missing.length||a.p.id.localeCompare(b.p.id));

const report={
  cityId,
  basis:'Generated by scripts/generate-enrichment-report.mjs from places.json, anchors.json and routes.json. high = top place or editorial route stop; medium = other curated anchors and OSM places with Wikidata or an editorial description; low = rest of the broad catalogue (counted, not listed).',
  summary:{
    places:places.length,
    byPriority:Object.fromEntries(Object.keys(order).map(k=>[k,rows.filter(r=>r.priority===k).length])),
    missingAll:countMissing(rows),
    missingHigh:countMissing(rows.filter(r=>r.priority==='high')),
    completeHigh:rows.filter(r=>r.priority==='high'&&!r.missing.length).length
  },
  priorityPlaces:listed.map(({p,missing,priority})=>({
    id:p.id,name:p.name,categoryId:p.categoryId,area:p.area||null,priority,
    curated:anchorIds.has(p.id),routes:routeCount(p.id),missing,
    osm:p.metadata?.source?.url||null,wikidata:p.metadata?.osmTags?.wikidata||null
  }))
};
await writeFile(`${base}/enrichment-report.json`,JSON.stringify(report,null,2)+'\n');
console.log(`Enrichment report for ${cityId}: ${listed.length} priority places listed.`);
