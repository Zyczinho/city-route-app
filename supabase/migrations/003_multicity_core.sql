-- City Route v2 foundation: multi-city catalogue, global taxonomy, routes and PostGIS.
-- Safe to run after 001_auth_community.sql and 002_message_sequence_permissions.sql.
-- Existing profile/group/chat tables are intentionally left untouched.

create schema if not exists extensions;
create extension if not exists postgis with schema extensions;

create table if not exists public.cities (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name text not null,
  country text not null,
  country_code text not null check (char_length(country_code)=2),
  locale text not null default 'pl-PL',
  currency text not null default 'PLN' check (char_length(currency)=3),
  timezone text not null,
  center extensions.geography(POINT) not null,
  default_zoom smallint not null default 12 check (default_zoom between 1 and 20),
  radius_km numeric(6,2) not null default 40 check (radius_km>0),
  status text not null default 'planned' check (status in ('launch','beta','next','planned','hidden')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.place_categories (
  id text primary key check (id ~ '^[a-z0-9_]+$'),
  group_id text not null check (group_id in ('sightseeing','nature','food','nightlife','activities','stay')),
  label_pl text not null,
  sort_order integer not null default 0,
  active boolean not null default true
);

create table if not exists public.places (
  id uuid primary key default gen_random_uuid(),
  city_id uuid not null references public.cities(id) on delete cascade,
  slug text not null check (slug ~ '^[a-z0-9-]+$'),
  name text not null check (char_length(name) between 1 and 160),
  category_id text not null references public.place_categories(id),
  location extensions.geography(POINT) not null,
  area text not null default '',
  description text not null default '',
  minutes integer not null default 20 check (minutes between 0 and 1440),
  cost_minor integer not null default 0 check (cost_minor>=0),
  currency text not null default 'PLN' check (char_length(currency)=3),
  tourist_level text not null default 'balanced' check (tourist_level in ('must','balanced','local')),
  food_style text not null default 'none' check (food_style in ('none','quick','sit')),
  partner boolean not null default false,
  is_top boolean not null default false,
  visibility text not null default 'public' check (visibility in ('public','unlisted','private')),
  status text not null default 'published' check (status in ('draft','published','archived')),
  created_by uuid references auth.users(id) on delete set null,
  image_url text,
  image_meta jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(city_id,slug)
);

create table if not exists public.place_tags (
  place_id uuid not null references public.places(id) on delete cascade,
  tag text not null check (tag ~ '^[a-z0-9_-]+$'),
  primary key(place_id,tag)
);

create table if not exists public.place_sources (
  id bigint generated by default as identity primary key,
  place_id uuid not null references public.places(id) on delete cascade,
  source text not null,
  external_id text,
  listing text not null default '',
  url text,
  rating numeric(4,2),
  rating_max numeric(4,2),
  review_count integer check (review_count is null or review_count>=0),
  checked_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  unique(place_id,source)
);

create table if not exists public.routes (
  id uuid primary key default gen_random_uuid(),
  city_id uuid not null references public.cities(id) on delete cascade,
  slug text,
  name text not null check (char_length(name) between 1 and 160),
  description text not null default '',
  route_type text not null default 'community' check (route_type in ('editorial','community')),
  owner_user_id uuid references auth.users(id) on delete set null,
  visibility text not null default 'public' check (visibility in ('public','unlisted','private')),
  status text not null default 'draft' check (status in ('draft','published','archived')),
  transport text not null default 'walking' check (transport in ('walking','bike','transit','mix')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(city_id,slug)
);

create table if not exists public.route_stops (
  route_id uuid not null references public.routes(id) on delete cascade,
  place_id uuid not null references public.places(id) on delete restrict,
  position integer not null check (position>=0),
  note text not null default '',
  primary key(route_id,position),
  unique(route_id,place_id)
);

create table if not exists public.route_tags (
  route_id uuid not null references public.routes(id) on delete cascade,
  tag text not null check (tag ~ '^[a-z0-9_-]+$'),
  primary key(route_id,tag)
);

create index if not exists cities_geo_idx on public.cities using gist(center);
create index if not exists places_city_idx on public.places(city_id,status);
create index if not exists places_category_idx on public.places(city_id,category_id,status);
create index if not exists places_geo_idx on public.places using gist(location);
create index if not exists places_name_idx on public.places(city_id,name);
create index if not exists place_tags_tag_idx on public.place_tags(tag,place_id);
create index if not exists routes_city_idx on public.routes(city_id,status,visibility);
create index if not exists routes_owner_idx on public.routes(owner_user_id);
create index if not exists route_stops_place_idx on public.route_stops(place_id);

