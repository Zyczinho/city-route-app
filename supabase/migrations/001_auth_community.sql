-- City Route: account, profile, groups and realtime chat foundation.
-- Run in Supabase SQL Editor once for the City Route project.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null default 'Odkrywca' check (char_length(nickname) between 1 and 40),
  bio text not null default '' check (char_length(bio) <= 160),
  stay text check (stay is null or stay in ('resident','temporary','visitor')),
  instagram text not null default '',
  tiktok text not null default '',
  website text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.explorer_groups (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 2 and 80),
  description text not null default '' check (char_length(description) <= 500),
  created_by uuid not null references auth.users(id) on delete cascade,
  is_public boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.group_members (
  group_id uuid not null references public.explorer_groups(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('member','moderator','owner')),
  joined_at timestamptz not null default now(),
  primary key (group_id,user_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  group_id uuid not null references public.explorer_groups(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists group_members_user_idx on public.group_members(user_id);
create index if not exists messages_group_created_idx on public.messages(group_id,created_at desc);
create index if not exists messages_user_idx on public.messages(user_id);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at=now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path=public
as $$
begin
  insert into public.profiles(id,nickname)
  values(new.id,coalesce(nullif(new.raw_user_meta_data->>'nickname',''),'Odkrywca'))
  on conflict(id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.add_group_owner()
returns trigger
language plpgsql
security definer set search_path=public
as $$
begin
  insert into public.group_members(group_id,user_id,role)
  values(new.id,new.created_by,'owner')
  on conflict(group_id,user_id) do update set role='owner';
  return new;
end;
$$;

drop trigger if exists on_group_created on public.explorer_groups;
create trigger on_group_created
after insert on public.explorer_groups
for each row execute function public.add_group_owner();

alter table public.profiles enable row level security;
alter table public.explorer_groups enable row level security;
alter table public.group_members enable row level security;
alter table public.messages enable row level security;

revoke all on table public.profiles from anon, authenticated;
revoke all on table public.explorer_groups from anon, authenticated;
revoke all on table public.group_members from anon, authenticated;
revoke all on table public.messages from anon, authenticated;

grant select, insert, update on table public.profiles to authenticated;
grant select, insert, update, delete on table public.explorer_groups to authenticated;
grant select, insert, update, delete on table public.group_members to authenticated;
grant select, insert, delete on table public.messages to authenticated;

drop policy if exists profiles_select_authenticated on public.profiles;
create policy profiles_select_authenticated on public.profiles
for select to authenticated
using (true);

drop policy if exists profiles_insert_own on public.profiles;
create policy profiles_insert_own on public.profiles
for insert to authenticated
with check ((select auth.uid())=id);

drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles
for update to authenticated
using ((select auth.uid())=id)
with check ((select auth.uid())=id);

drop policy if exists groups_select_public_or_owned on public.explorer_groups;
create policy groups_select_public_or_owned on public.explorer_groups
for select to authenticated
using (is_public or created_by=(select auth.uid()));

drop policy if exists groups_insert_own on public.explorer_groups;
create policy groups_insert_own on public.explorer_groups
for insert to authenticated
with check (created_by=(select auth.uid()));

drop policy if exists groups_update_owner on public.explorer_groups;
create policy groups_update_owner on public.explorer_groups
for update to authenticated
using (created_by=(select auth.uid()))
with check (created_by=(select auth.uid()));

drop policy if exists groups_delete_owner on public.explorer_groups;
create policy groups_delete_owner on public.explorer_groups
for delete to authenticated
using (created_by=(select auth.uid()));

drop policy if exists members_select_public_groups on public.group_members;
create policy members_select_public_groups on public.group_members
for select to authenticated
using (exists (
  select 1 from public.explorer_groups g
  where g.id=group_id and (g.is_public or g.created_by=(select auth.uid()))
));

drop policy if exists members_join_self on public.group_members;
create policy members_join_self on public.group_members
for insert to authenticated
with check (
  user_id=(select auth.uid())
  and role='member'
  and exists (select 1 from public.explorer_groups g where g.id=group_id and g.is_public)
);

drop policy if exists members_leave_self on public.group_members;
create policy members_leave_self on public.group_members
for delete to authenticated
using (user_id=(select auth.uid()) and role<>'owner');

drop policy if exists members_owner_manage on public.group_members;
create policy members_owner_manage on public.group_members
for update to authenticated
using (exists (
  select 1 from public.explorer_groups g
  where g.id=group_id and g.created_by=(select auth.uid())
))
with check (exists (
  select 1 from public.explorer_groups g
  where g.id=group_id and g.created_by=(select auth.uid())
));

drop policy if exists messages_select_members on public.messages;
create policy messages_select_members on public.messages
for select to authenticated
using (exists (
  select 1 from public.group_members gm
  where gm.group_id=messages.group_id and gm.user_id=(select auth.uid())
));

drop policy if exists messages_insert_members on public.messages;
create policy messages_insert_members on public.messages
for insert to authenticated
with check (
  user_id=(select auth.uid())
  and exists (
    select 1 from public.group_members gm
    where gm.group_id=messages.group_id and gm.user_id=(select auth.uid())
  )
);

drop policy if exists messages_delete_own on public.messages;
create policy messages_delete_own on public.messages
for delete to authenticated
using (user_id=(select auth.uid()));

-- Enable realtime for chat messages once, without failing if re-run.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname='supabase_realtime' and schemaname='public' and tablename='messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end $$;
